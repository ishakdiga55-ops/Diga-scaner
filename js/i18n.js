export function applyLanguage(lang) {
  const isAr = lang === 'ar';
  document.documentElement.lang = lang;
  document.documentElement.dir = isAr ? 'rtl' : 'ltr';
  
  const dict = translations[lang];
  
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (dict[key]) {
      if (el.tagName === 'INPUT' && el.hasAttribute('placeholder')) {
        el.placeholder = dict[key];
      } else {
        const icon = el.querySelector('i');
        if (icon) {
          el.innerHTML = icon.outerHTML + ' ' + dict[key];
        } else {
          el.textContent = dict[key];
        }
      }
    }
  });

  const langBtn = document.getElementById('langBtn');
  if (langBtn) langBtn.textContent = isAr ? 'FR' : 'AR';
  
  const consoleEl = document.getElementById('console');
  if (consoleEl && consoleEl.textContent.trim() === '> جاهز!') {
      consoleEl.textContent = dict.consoleReady;
  } else if (consoleEl && consoleEl.textContent.trim() === '> Prêt!') {
      consoleEl.textContent = dict.consoleReady;
  }

  localStorage.setItem('checkdiga_lang', lang);
}

export function initLang() {
  const savedLang = localStorage.getItem('checkdiga_lang') || 'ar';
  applyLanguage(savedLang);
  
  const langBtn = document.getElementById('langBtn');
  if (langBtn) {
    langBtn.onclick = () => {
      const current = localStorage.getItem('checkdiga_lang') || 'ar';
      const next = current === 'ar' ? 'fr' : 'ar';
      applyLanguage(next);
    };
  }
}